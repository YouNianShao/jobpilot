"""浏览器抽象：Page / BrowserDriver 两个协议。

真实实现用 patchright 连接用户已登录的 Chrome；测试用 fake 实现。
服务层与平台驱动只依赖这里的协议，不依赖具体实现。
"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class Page(Protocol):
    @property
    def url(self) -> str: ...

    @property
    def title(self) -> str: ...

    def goto(self, url: str) -> None: ...
    def text(self) -> str: ...
    def html(self) -> str: ...
    def eval(self, js: str) -> Any: ...
    def click(self, selector: str, timeout_ms: int = 8000) -> None: ...
    def fill(self, selector: str, value: str) -> None: ...
    def inner_text(self, selector: str) -> str: ...
    def exists(self, selector: str) -> bool: ...
    def wait_for(self, selector: str, timeout_ms: int = 8000) -> bool: ...
    def screenshot(self, path: str) -> None: ...
    def close(self) -> None: ...


@runtime_checkable
class BrowserDriver(Protocol):
    def health(self) -> bool: ...
    def open(self, url: str) -> Page: ...
    def find(self, url_contains: str) -> Page | None: ...
    def close(self) -> None: ...
